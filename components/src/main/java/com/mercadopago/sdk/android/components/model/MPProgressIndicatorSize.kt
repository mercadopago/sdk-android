package com.mercadopago.sdk.android.components.model

/**
 * Progress Indicator size enum class, used to determine the indicator dimensions
 * This is used to control the indicator's size and stroke width
 */
enum class MPProgressIndicatorSize {
    /**
     * XSmall: Extra small indicator size
     */
    XSmall,

    /**
     * Small: Smaller indicator size
     */
    Small,

    /**
     * Medium: Medium indicator size
     */
    Medium,

    /**
     * Large: Larger indicator size
     */
    Large,

    /**
     * XLarge: Extra large indicator size
     */
    XLarge,
}
